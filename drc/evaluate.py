"""Offline evaluation on worlds the demo never uses. Writes docs/evaluation.md.

    python -m drc.evaluate
"""
import pathlib
import random

import numpy as np

from . import engine, seed, world


def storms(n_worlds=40, per_world=5):
    """Isolation forecast made at hour 0, scored at peak against storms drawn from the forecast distribution,
    with the true (not surveyed) elevations and the debris closures the model does not know about."""
    rng, p_all, naive_all, y_all = np.random.default_rng(1), [], [], []
    for s in range(300, 300 + n_worlds):
        w = world.build(s)
        hosp = [h["node"] for h in w["hospitals"]]
        p, _ = engine.isolation_risk(w, 0, world.PEAK_HOUR, hosp, seed=s)
        naive = engine.naive_risk(w, 0, world.PEAK_HOUR)
        for _ in range(per_world):
            peak = rng.normal(world.FORECAST_PEAK, world.FORECAST_SD)
            y_all.append(engine.isolated(w, world.closed(w, peak, world.PEAK_HOUR, w["elev_true"], w["debris"]), hosp))
            p_all.append(p)
            naive_all.append(naive)
    return np.concatenate(p_all), np.concatenate(naive_all), np.concatenate(y_all).astype(float)


def dispatch(n_worlds=40):
    out = []
    for s in range(300, 300 + n_worlds):
        w = world.build(s)
        r = random.Random(s)
        inc = [i for i in w["incidents"] if i["hour"] in (5, 6)]
        r.shuffle(inc)
        closed = world.closed(w, world.TRUE_PEAK, 6, w["elev_true"], w["debris"])
        eta = engine.etas(w, closed, [(u["node"], u["type"]) for u in w["units"]], [(i["node"], i["type"]) for i in inc])
        sev = [i["severity"] for i in inc]
        out.append((engine.score(sev, eta, engine.assign(sev, eta)), engine.score(sev, eta, engine.greedy(eta)), len(inc)))
    return out


def merging(radius, n_worlds=40):
    """Replay the report stream through the merge rule (same type, within `radius` blocks, within two hours)."""
    rows = lost = true = 0
    for s in range(300, 300 + n_worlds):
        w = world.build(s)
        opened = []                                  # (type, x, y, hour, truth index of the report that opened it)
        for rep in w["reports"]:
            if rep["incident"] is None:
                continue
            kind, x, y = w["incidents"][rep["incident"]]["type"], rep["node"] % world.W, rep["node"] // world.W
            if not any(k == kind and abs(x - a) + abs(y - b) <= radius and rep["hour"] - h <= 2 for k, a, b, h, _ in opened):
                opened.append((kind, x, y, rep["hour"], rep["incident"]))
        owners = {o[4] for o in opened}
        rows, lost, true = rows + len(opened), lost + len(w["incidents"]) - len(owners), true + len(w["incidents"])
    return {"true": true, "rows": rows, "lost": lost, "duplicates": rows - (true - lost)}


def main():
    _, m = seed.train()
    p, naive, y = storms()
    brier = lambda q: float(((q - y) ** 2).mean())      # noqa: E731
    bins = [(0, 0.1), (0.1, 0.3), (0.3, 0.7), (0.7, 0.9), (0.9, 1.01)]
    d = dispatch()
    red = [1 - a["weighted_wait"] / b["weighted_wait"] for a, b, _ in d]
    eta = lambda k: np.mean([x[k]["severe_mean_eta_s"] for x in d]) / 60      # noqa: E731
    m0, m1 = merging(0), merging(1)
    lines = ["# Evaluation", "",
             "Generated by `python -m drc.evaluate` on 40 synthetic counties (seeds 300 to 339) that the demo and the tests never use.",
             "Everything is simulated, so each engine has a known right answer. Read these as a check that the engines work, not as field accuracy.", "",
             "## 1. Citizen-report classifier", "",
             f"Character n-gram TF-IDF + logistic regression over five classes, fitted on one synthetic corpus and scored on {m['model']['n_test']:,} reports of another.", "",
             "| | Accuracy |", "|---|---|", f"| Classifier | {m['model']['accuracy']:.1%} |", f"| Baseline: keyword rules | {m['baseline']['accuracy']:.1%} |", "",
             "The reports come from a phrase bank of about ten sentences per class with openers, closers and dropped letters, which is why the classifier is perfect.",
             "Real reports would not be. The keyword rules fail mostly on reports that mention water for another reason (a burst main, a flooded room with a medical emergency).", "",
             "## 2. Isolation forecast", "",
             f"A forecast made six hours before peak surge, scored against {len(y) // world.N} simulated storms ({len(y):,} neighbourhood outcomes, {y.mean():.1%} isolated).",
             "The truth uses the real elevations (the survey is off by about 0.25 m) and four debris closures per county that no flood model predicts.", "",
             "| | Brier score (lower is better) |", "|---|---|", f"| Monte Carlo over surge peak and survey error (300 samples) | {brier(p):.4f} |",
             f"| Baseline: survey elevation below the forecast water level | {brier(naive):.4f} |", f"| Always predicting the base rate | {brier(np.full_like(y, y.mean())):.4f} |", "",
             "Calibration of the Monte Carlo forecast:", "", "| Predicted chance | Neighbourhoods | Mean predicted | Actually isolated |", "|---|---|---|---|"]
    for lo, hi in bins:
        k = (p >= lo) & (p < hi)
        lines.append(f"| {lo:.0%} to {min(hi, 1):.0%} | {int(k.sum()):,} | {p[k].mean():.1%} | {y[k].mean():.1%} |")
    lines += ["", "The lowest bin is where the unmodelled debris closures show up: the model says almost never, and it happens a little more often than that.", "",
              "## 3. Dispatch", "",
              f"One snapshot per county at peak surge: the incidents of the last two hours ({np.mean([n for *_, n in d]):.0f} on average) against 24 units at their stations.", "",
              "| | Exact assignment | Report order, nearest unit |", "|---|---|---|",
              f"| Severity-weighted wait (relative) | {1 - np.mean(red):.3f} | 1.000 |", f"| Mean time to reach a severity 4 to 5 incident | {eta(0):.1f} min | {eta(1):.1f} min |",
              f"| Severity 4 to 5 incidents left without a unit, all counties | {sum(a['severe_unserved'] for a, _, _ in d)} | {sum(b['severe_unserved'] for _, b, _ in d)} |", "",
              f"The weighted wait fell in {sum(x > 1e-9 for x in red)} of {len(red)} counties and never rose (the assignment is exact for this objective). Range of the reduction: {min(red):.1%} to {max(red):.1%}.", "",
              "## 4. Merging reports into incidents", "",
              "Several people report the same emergency, and a fifth of reports are located one block off. The merge rule decides how many incidents the dispatcher sees.", "",
              "| Rule | True incidents | Incident rows opened | True incidents with no row of their own | Duplicate rows |", "|---|---|---|---|---|",
              f"| Same type, same block (used) | {m0['true']:,} | {m0['rows']:,} | {m0['lost']:,} | {m0['duplicates']:,} |",
              f"| Same type, within one block | {m1['true']:,} | {m1['rows']:,} | {m1['lost']:,} | {m1['duplicates']:,} |", "",
              "Neither is right. See the README's tradeoff section for why the narrower rule is used and what it costs."]
    out = pathlib.Path(__file__).resolve().parent.parent / "docs" / "evaluation.md"
    out.write_text("\n".join(lines) + "\n")
    print(out.read_text())


if __name__ == "__main__":
    main()
